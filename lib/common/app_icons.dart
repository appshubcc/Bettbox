class AppIconScope extends InheritedWidget {
  final bool usePhosphorIcons;

  const AppIconScope({
    super.key,
    required this.usePhosphorIcons,
    required super.child,
  });

  static bool of(BuildContext context) =>
      context
          .dependOnInheritedWidgetOfExactType<AppIconScope>()
          ?.usePhosphorIcons ??
      false;

  @override
  bool updateShouldNotify(AppIconScope oldWidget) =>
      usePhosphorIcons != oldWidget.usePhosphorIcons;
}

IconData resolveIcon(IconData icon, {bool enabled = false}) =>
    _resolveIcon(icon, enabled: enabled);

IconData _resolveIcon(IconData icon, {required bool enabled}) {
  if (!enabled) return icon;
  return _phosphorIconMap[icon] ?? icon;
}

Widget? resolveIconWidget(Widget? widget, {bool enabled = false}) =>
    _resolveIconWidget(widget, enabled: enabled);

Widget? _resolveIconWidget(Widget? widget, {required bool enabled}) {
  if (!enabled || widget is! Icon) return widget;
  final iconData = widget.icon;
  if (iconData == null) return widget;
  final mapped = _phosphorIconMap[iconData];
  if (mapped == null) return widget;
  return Icon(
    mapped,
    key: widget.key,
    size: widget.size,
    fill: widget.fill,
    weight: widget.weight,
    grade: widget.grade,
    opticalSize: widget.opticalSize,
    color: widget.color,
    shadows: widget.shadows,
    semanticLabel: widget.semanticLabel,
    textDirection: widget.textDirection,
    applyTextScaling: widget.applyTextScaling,
  );
}

class AppIcon extends StatelessWidget {
  final IconData? icon;
  final double? size;
  final Color? color;
  final double? fill;
  final double? weight;
  final double? grade;
  final double? opticalSize;
  final List<Shadow>? shadows;
  final String? semanticLabel;
  final TextDirection? textDirection;
  final bool? applyTextScaling;

  const AppIcon(
    this.icon, {
    super.key,
    this.size,
    this.color,
    this.fill,
    this.weight,
    this.grade,
    this.opticalSize,
    this.shadows,
    this.semanticLabel,
    this.textDirection,
    this.applyTextScaling,
  });

  @override
  Widget build(BuildContext context) {
    final icon = this.icon;
    return Icon(
      icon == null ? null : context.resolveIcon(icon),
      size: size,
      color: color,
      fill: fill,
      weight: weight,
      grade: grade,
      opticalSize: opticalSize,
      shadows: shadows,
      semanticLabel: semanticLabel,
      textDirection: textDirection,
      applyTextScaling: applyTextScaling,
    );
  }
}

extension BuildContextIconExt on BuildContext {
  IconData resolveIcon(IconData icon) =>
      _resolveIcon(icon, enabled: AppIconScope.of(this));

  Widget? resolveIconWidget(Widget? widget) =>
      _resolveIconWidget(widget, enabled: AppIconScope.of(this));
}
