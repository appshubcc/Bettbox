#!/usr/bin/env python3
"""Generate the Reicons icon font from the ReIcons.* names used in lib/.

Icons come from reicon_flutter (https://reicon.dev, MIT). `ReIcons.fooBar`
uses the Outline weight, `ReIcons.fooBarFilled` the Filled weight.

Usage:
    pip install fonttools picosvg skia-pathops
    python3 tool/reicons.py
"""

import io
import re
import tarfile
import urllib.request
from pathlib import Path

import pathops
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path
from picosvg.svg import SVG

PACKAGE = 'https://pub.dev/api/archives/reicon_flutter-1.0.1.tar.gz'
ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'assets/fonts/Reicons.ttf'
DART = ROOT / 'lib/common/reicons.dart'
FAMILY = 'Reicons'
UPM = 1024
FIRST_CODEPOINT = 0xE000


def load_icons():
    with urllib.request.urlopen(PACKAGE) as res:
        archive = tarfile.open(fileobj=io.BytesIO(res.read()))
    src = archive.extractfile('lib/src/icons.dart').read().decode()
    weights = {}
    for weight in ('outline', 'filled'):
        start = src.index(f'final Map<String, String> _{weight}')
        end = src.index('};', start)
        weights[weight] = dict(
            re.findall(r"^  '([^']+)': r'''(.*?)''',?$", src[start:end], re.M | re.S)
        )
    return weights


def used_names():
    names = set()
    for file in (ROOT / 'lib').rglob('*.dart'):
        if file != DART:
            names.update(re.findall(r'\bReIcons\.(\w+)', file.read_text()))
    return sorted(names)


def draw_glyph(markup):
    svg = SVG.fromstring(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" '
        f'fill="none" color="#000">{markup.replace("currentColor", "#000")}</svg>'
    ).topicosvg()
    paths = []
    for shape in svg.shapes():
        path = pathops.Path()
        parse_path(shape.as_path().d, path.getPen())
        paths.append(path)
    merged = pathops.Path()
    pathops.union(paths, merged.getPen())
    pen = TTGlyphPen(None)
    scale = UPM / 24
    # SVG is y-down on a 24px grid; fonts are y-up with the baseline at 0.
    merged.draw(
        Cu2QuPen(
            TransformPen(pen, (scale, 0, 0, -scale, 0, UPM)),
            max_err=1,
            reverse_direction=True,
        )
    )
    return pen.glyph()


def build_font(names, icons):
    glyph_names = ['.notdef'] + names
    glyphs = {'.notdef': TTGlyphPen(None).glyph()}
    cmap = {}
    for index, name in enumerate(names):
        filled = name.endswith('Filled')
        key = name[: -len('Filled')] if filled else name
        markup = icons['filled' if filled else 'outline'].get(key)
        if markup is None:
            raise SystemExit(f'Unknown reicon: ReIcons.{name}')
        glyphs[name] = draw_glyph(markup)
        cmap[FIRST_CODEPOINT + index] = name

    builder = FontBuilder(UPM, isTTF=True)
    builder.setupGlyphOrder(glyph_names)
    builder.setupCharacterMap(cmap)
    builder.setupGlyf(glyphs)
    builder.setupHorizontalMetrics({name: (UPM, 0) for name in glyph_names})
    builder.setupHorizontalHeader(ascent=UPM, descent=0)
    builder.setupNameTable({'familyName': FAMILY, 'styleName': 'Regular'})
    builder.setupOS2(sTypoAscender=UPM, sTypoDescender=0, usWinAscent=UPM, usWinDescent=0)
    builder.setupPost()
    builder.save(FONT)


def write_dart(names):
    lines = [
        '// Generated by tool/reicons.py from https://reicon.dev (MIT). Do not edit.',
        "import 'package:material_ui/material_ui.dart';",
        '',
        'abstract final class ReIcons {',
    ]
    for index, name in enumerate(names):
        code = FIRST_CODEPOINT + index
        lines.append(
            f"  static const IconData {name} = IconData(0x{code:x}, fontFamily: '{FAMILY}');"
        )
    lines.append('}')
    DART.write_text('\n'.join(lines) + '\n')


def main():
    names = used_names()
    build_font(names, load_icons())
    write_dart(names)
    print(f'{len(names)} icons -> {FONT.relative_to(ROOT)}, {DART.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
